#Requires -Version 7.0
<#
.SYNOPSIS
    OEM branding: wallpaper, oemlogo, OEM registry, readme.

.DESCRIPTION
    Brand values are fixed by the user-approved design (docs/design.md
    §5.5) and must not drift:

        OEMInformation  Manufacturer=MICPE, Model=SYSTEM-Intel-MIC,
                        SupportURL=https://space.bilibili.com/1978487514,
                        SupportProvider=SYSTEM-Intel-MIC,
                        Logo=%SystemRoot%\System32\oemlogo.bmp
        CurrentVersion  RegisteredOwner=SYSTEM-Intel-MIC,
                        RegisteredOrganization=MICPE
        ComputerName    MICPE-XXXX

    The .reg text is generated by Get-BrandRegContent (pure function, so
    tests can pin every value) and imported through the shared
    Invoke-RegistryScript path. The committed src/registry/50-brand.reg
    is the generated output for the default inputs; a test fails if it
    drifts from Get-BrandRegContent.

    .reg conventions follow the existing patches (20-explorer.reg): UTF-16LE
    with BOM, LF line endings, doubled backslashes inside string values
    (reg.exe import un-escapes them), single backslashes in key paths.

    // reuse-check: key paths and values are design.md §5.5 verbatim;
    the BMP header read (bytes 18..26) is plan T14 verbatim.
#>

function Get-BrandRegContent {
    [CmdletBinding()]
    param(
        [string] $Version = '1.0.0',

        [string] $BuildNumber = '26300.10075',

        [string] $ComputerName = 'MICPE-XXXX'
    )

    $lines = @(
        'Windows Registry Editor Version 5.00'
        '; MICPE brand registry patch (M5).'
        "; Version $Version build $BuildNumber"
        '; Generated by Get-BrandRegContent; the committed src/registry/50-brand.reg must match this output for the default inputs.'
        ''
        '[HKEY_LOCAL_MACHINE\PE-SOFT\Microsoft\Windows\CurrentVersion\OEMInformation]'
        '"Manufacturer"="MICPE"'
        '"Model"="SYSTEM-Intel-MIC"'
        '"SupportURL"="https://space.bilibili.com/1978487514"'
        '"SupportProvider"="SYSTEM-Intel-MIC"'
        '"Logo"="%SystemRoot%\\System32\\oemlogo.bmp"'
        ''
        '[HKEY_LOCAL_MACHINE\PE-SOFT\Microsoft\Windows NT\CurrentVersion]'
        '"RegisteredOwner"="SYSTEM-Intel-MIC"'
        '"RegisteredOrganization"="MICPE"'
        ''
        '[HKEY_LOCAL_MACHINE\PE-SYS\ControlSet001\Control\ComputerName\ComputerName]'
        "`"ComputerName`"=`"$ComputerName`""
    )

    return ($lines -join "`n")
}

function Get-BrandReadmeContent {
    [CmdletBinding()]
    param(
        [string] $Version = '1.0.0',

        [string] $BuildNumber = '26300.10075'
    )

    $lines = @(
        'MICPE 装机维修盘'
        "版本：$Version"
        "构建号：$BuildNumber"
        '作者：SYSTEM-Intel-MIC'
        '主页：https://space.bilibili.com/1978487514'
        ''
        '本映像基于 Windows 11 26H2 制作，仅供学习与维修使用。'
    )

    return ($lines -join "`r`n")
}

function Get-BmpDimensions {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [string] $Path
    )

    Assert-PathExists -Path $Path -Label 'BMP file'
    $bytes = [System.IO.File]::ReadAllBytes($Path)
    if ($bytes.Length -lt 30 -or $bytes[0] -ne 0x42 -or $bytes[1] -ne 0x4D) {
        throw [System.InvalidOperationException]::new("not a BMP file: $Path")
    }

    return [pscustomobject]@{
        Width        = [System.BitConverter]::ToInt32($bytes, 18)
        Height       = [System.BitConverter]::ToInt32($bytes, 22)
        BitsPerPixel = [System.BitConverter]::ToInt16($bytes, 28)
    }
}

function Set-Brand {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [string] $MountDir,

        [Parameter(Mandatory = $true)]
        [string] $RepoRoot,

        [string] $Version = '1.0.0',

        [string] $BuildNumber = '26300.10075',

        [string] $ComputerName = 'MICPE-XXXX'
    )

    Assert-PathExists -Path $MountDir -Label 'boot.wim mount'
    $assets = Join-Path $RepoRoot 'assets'
    $wallpaperSrc = Join-Path $assets 'wallpaper.jpg'
    $logoSrc = Join-Path $assets 'logo.bmp'
    Assert-PathExists -Path $wallpaperSrc -Label 'wallpaper.jpg'
    Assert-PathExists -Path $logoSrc -Label 'logo.bmp'

    $wallpaperDestDir = Join-Path $MountDir 'Windows/Web/Wallpaper/Windows'
    New-Item -ItemType Directory -Path $wallpaperDestDir -Force | Out-Null
    Copy-Item -LiteralPath $wallpaperSrc -Destination (Join-Path $wallpaperDestDir 'img0.jpg') -Force
    Write-SubStep 'wallpaper installed as img0.jpg'

    $system32 = Join-Path $MountDir 'Windows/System32'
    New-Item -ItemType Directory -Path $system32 -Force | Out-Null
    Copy-Item -LiteralPath $logoSrc -Destination (Join-Path $system32 'oemlogo.bmp') -Force
    Write-SubStep 'oemlogo.bmp installed'

    $micpeDir = Join-Path $MountDir 'Program Files/MICPE'
    New-Item -ItemType Directory -Path $micpeDir -Force | Out-Null
    $readme = Join-Path $micpeDir '说明.txt'
    $utf8Bom = [System.Text.UTF8Encoding]::new($true)
    [System.IO.File]::WriteAllText(
        $readme, (Get-BrandReadmeContent -Version $Version -BuildNumber $BuildNumber), $utf8Bom)
    Write-SubStep 'Program Files/MICPE/说明.txt written'

    # Registry: generate the patch to a temp file (UTF-16LE with BOM) and
    # import it through the shared path. The committed 50-brand.reg is the
    # same generated text for the default inputs.
    $regText = Get-BrandRegContent -Version $Version -BuildNumber $BuildNumber -ComputerName $ComputerName
    $tempReg = [System.IO.Path]::ChangeExtension([System.IO.Path]::GetTempFileName(), '.reg')
    try {
        $utf16 = [System.Text.UnicodeEncoding]::new($false, $true)
        [System.IO.File]::WriteAllText($tempReg, $regText, $utf16)
        Invoke-RegistryScript -MountDir $MountDir -RegFiles @($tempReg)
    }
    finally {
        if (Test-Path -LiteralPath $tempReg) {
            Remove-Item -LiteralPath $tempReg -Force -ErrorAction SilentlyContinue
        }
    }
    Write-SubStep 'brand registry imported'
}

function Assert-BrandApplied {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [string] $MountDir
    )

    $missing = [System.Collections.Generic.List[string]]::new()

    $logo = Join-Path $MountDir 'Windows/System32/oemlogo.bmp'
    if (-not (Test-Path -LiteralPath $logo)) {
        $missing.Add('Windows/System32/oemlogo.bmp')
    }
    else {
        $dims = Get-BmpDimensions -Path $logo
        if ($dims.Width -ne 120 -or $dims.Height -ne 120) {
            $missing.Add("oemlogo.bmp is $($dims.Width)x$($dims.Height), need 120x120")
        }
    }

    $wallpaper = Join-Path $MountDir 'Windows/Web/Wallpaper/Windows/img0.jpg'
    if (-not (Test-Path -LiteralPath $wallpaper)) {
        $missing.Add('Windows/Web/Wallpaper/Windows/img0.jpg')
    }

    $readme = Join-Path $MountDir 'Program Files/MICPE/说明.txt'
    if (-not (Test-Path -LiteralPath $readme)) {
        $missing.Add('Program Files/MICPE/说明.txt')
    }
    else {
        $text = Get-Content -LiteralPath $readme -Raw -Encoding UTF8
        foreach ($marker in 'MICPE', 'SYSTEM-Intel-MIC', 'space.bilibili.com/1978487514') {
            if ($text -notmatch [regex]::Escape($marker)) {
                $missing.Add("说明.txt is missing '$marker'")
            }
        }
    }

    if ($missing.Count -gt 0) {
        throw [System.InvalidOperationException]::new(
            "Brand is incomplete. Missing:`n  " + ($missing -join "`n  "))
    }

    Write-SubStep 'brand artifacts verified'
}
